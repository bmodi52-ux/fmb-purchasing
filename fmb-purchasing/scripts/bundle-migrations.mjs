/**
 * Every migration, in order, as one file to paste into a brand-new project.
 *
 *   node scripts/bundle-migrations.mjs --out sandbox-schema.sql
 *   node scripts/bundle-migrations.mjs | clip
 *
 * Setting up a new database — the sandbox, or a scratch project for a restore
 * rehearsal — means running all of them in order, and 58 separate pastes into
 * the SQL editor is how one gets missed. This is the same files, concatenated,
 * with a header before each so an error message still names the migration it
 * came from.
 *
 * combined_bootstrap.sql is deliberately left out: it is an alternative to
 * 0001 rather than an addition to it, and including both would run the initial
 * schema twice.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql") && f !== "combined_bootstrap.sql")
  .sort();

const parts = [
  "-- FMB Purchasing: every migration in order, generated by scripts/bundle-migrations.mjs",
  "-- " + files.length + " migrations, " + files[0] + " through " + files[files.length - 1],
  "-- Run this once against a new, empty project. Do not run it against a database that has any of them already.",
  "",
];

for (const file of files) {
  parts.push("-- ===================================================================");
  parts.push("-- " + file);
  parts.push("-- ===================================================================");
  parts.push(readFileSync(new URL(file, dir), "utf8").replace(/\s*$/, ""));
  parts.push("");
}

const sql = parts.join("\n") + "\n";
const outFlag = process.argv.indexOf("--out");
if (outFlag !== -1 && process.argv[outFlag + 1]) {
  const target = path.resolve(process.argv[outFlag + 1]);
  writeFileSync(target, sql);
  console.error(files.length + " migrations written to " + target);
} else {
  process.stdout.write(sql);
}
